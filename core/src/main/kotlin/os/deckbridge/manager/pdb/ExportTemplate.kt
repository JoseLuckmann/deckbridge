    /** Linha de histórico com a data (`AAAA-MM-DD`, 10 caracteres ASCII) trocada. */
    fun history(date: String): ByteArray {
        require(date.length == 10 && date.all { it.code < 128 }) { "data deve ter 10 caracteres ASCII" }
        val row = bytes(history)
        val at = 13
        date.forEachIndexed { n, c -> row[at + n] = c.code.toByte() }
        return row
